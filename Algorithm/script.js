// Area of A Triangle 
// Formula: 1/2 * b * h
let base = 12;
let height = 5;

let areaTriangle = 0.5 * base * height

console.log("The area of the traingle is: " + areaTriangle);

// Area of A Square
// Formula: l ** 2
let side = 10;

let areaSquare = side ** 2

console.log("The area of the square is: " + areaSquare);

// Area of A Circle
// Formula: Math.PI * r ** 2
let radius = 5;

let areaCircle = Math.PI * radius ** 2

console.log("The area of the circle is: " + areaCircle);

// Area of A Quadrilateral 
// Formula: 1/2 * d * (h1 + h2)
let d = 5;
let h1 = 4;
let h2 = 10;

let areaQuadrilateral = 0.5 * d * (h1 + h2);

console.log("The area of the quadrilateral is: " + areaQuadrilateral);

// Area of A Rhombus 
// Formula: 1/2 * d1 * d2
let d1 = 12;
let d2 = 5;

let areaRhombus = 0.5 * d1 * d2

console.log("The area of the rhombus is: " + areaRhombus);

// Area of A Trapezium
// Formula: 1/2 * (a + b) * h
let a = 12;
let b = 5;
let h = 20;

let areaTrapezium = 0.5 * (a + b) * h

console.log("The area of the trapezium is: " + areaTrapezium);

// Area of a Parallogram 
// Formula: 1/2 * b * h
let pbase = 12;
let pheight = 5;

let areaParallelogram = 0.5 * pbase * pheight

console.log("The area of the traingle is: " + areaParallelogram);

// Body Mass Index (BMI)
// Formula:BMi = weight in kg / (height in meters) ** 2
let weight = 12;
let userHeight = 5;

let bmi = weight / (userHeight) ** 2

console.log("The BMI is: " + bmi);

